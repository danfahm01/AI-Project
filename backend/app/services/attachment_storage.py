"""File storage for attachments (local disk; a Docker volume in production).

Keys are generated by the server (``<user id>/<attachment id>``), never taken
from user input, and are still resolved defensively inside the root directory.
"""

import asyncio
import logging
import os
import uuid
from pathlib import Path

logger = logging.getLogger(__name__)


class AttachmentStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    @staticmethod
    def key_for(user_id: uuid.UUID, attachment_id: uuid.UUID) -> str:
        return f"{user_id}/{attachment_id}"

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError("Invalid storage key")
        return path

    async def save(self, key: str, data: bytes) -> None:
        await asyncio.to_thread(self._write, self._path(key), data)

    @staticmethod
    def _write(path: Path, data: bytes) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.tmp")
        temporary.write_bytes(data)
        os.replace(temporary, path)  # atomic: readers never see a partial file

    async def read(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)

    async def delete(self, key: str) -> None:
        try:
            await asyncio.to_thread(self._path(key).unlink, missing_ok=True)
        except OSError:
            logger.warning("Could not delete attachment file %s", key, exc_info=True)

    async def delete_many(self, keys: list[str]) -> None:
        for key in keys:
            await self.delete(key)
